import Foundation
internal import FactoryKit

extension PrivyContainer {
    internal var loginWithSiws: Factory<LoginWithSiws> {
        self { LoginWithSiwsImpl() }.shared
    }
}

/// Methods used to login with a Solana wallet, or link one to a user, via Sign-In with Solana (SIWS)
public protocol LoginWithSiws: Sendable {
    /// Generates a SIWS message for the user to sign in order to prove ownership of the wallet
    ///
    /// - Parameters:
    ///   - params: Specifies the configuration options to build the SIWS message
    /// - Returns: A unique SIWS message as a string
    /// - Throws: An error if there was an issue generating the message
    func generateMessage(params: SiwsMessageParams) async throws -> String

    /// Log in the user with the SIWS signature
    ///
    /// - Parameters:
    ///   - message: The previously generated SIWS message
    ///   - signature: The SIWS signature generated by the wallet
    ///   - params: The wallet configuration used to generate the message. Without it, the
    ///     account-transfer-conflict flow cannot be triggered for this login.
    ///   - metadata: (Optional) Additional metadata specifying wallet client and connector type
    /// - Returns: The authenticated Privy user
    /// - Throws: An error if authenticating the user is unsuccessful
    func login(
        message: String,
        signature: String,
        params: SiwsMessageParams?,
        metadata: WalletLoginMetadata?
    ) async throws -> PrivyUser

    /// Links the user's external Solana wallet to the users account. User must be authenticated prior to calling this method.
    ///
    /// - Parameters:
    ///   - message: The previously generated SIWS message
    ///   - signature: The SIWS signature generated by the wallet
    ///   - params: The wallet configuration used to generate the message. Without it, the
    ///     account-transfer-conflict flow cannot be triggered for this link.
    ///   - metadata: (Optional) Additional metadata specifying wallet client and connector type
    /// - Returns: The updated Privy user with the newly linked wallet
    /// - Throws: An error if linking the user's wallet in is unsuccessful, or if there is no authenticated user
    func link(
        message: String,
        signature: String,
        params: SiwsMessageParams?,
        metadata: WalletLoginMetadata?
    ) async throws -> PrivyUser

    /// Unlinks the specified Solana wallet from the currently authenticated user's account.
    ///
    /// - Parameters:
    ///   - address: The Solana wallet address to unlink from the user.
    /// - Returns: The updated Privy user after unlinking the wallet
    /// - Throws: An error if unlinking the user's wallet is unsuccessful, or if there is no authenticated user.
    func unlink(address: String) async throws -> PrivyUser

    /// Transfers a Solana wallet account from another Privy user to the currently authenticated user.
    /// Call this after catching a `PrivyError` with reason `.accountTransferRequired` from `link`.
    ///
    /// - Parameters:
    ///   - nonce: The one-time transfer nonce from the `accountTransferRequired` error
    ///   - message: The SIWS message that was signed by the user's wallet
    ///   - signature: The signature produced by signing the message with the Solana wallet
    ///   - params: The wallet configuration used to generate the message
    ///   - metadata: (Optional) Additional metadata specifying wallet client and connector type
    /// - Returns: The updated Privy user after transferring the wallet account
    /// - Throws: An error if transferring the account is unsuccessful
    func transferAccount(
        nonce: String,
        message: String,
        signature: String,
        params: SiwsMessageParams,
        metadata: WalletLoginMetadata?
    ) async throws -> PrivyUser
}

public extension LoginWithSiws {
