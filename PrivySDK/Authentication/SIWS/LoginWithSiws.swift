private final class LoginWithSiwsImpl: LoginWithSiws {
    private let authManager: AuthManager = resolve(\PrivyContainer.authManager)
    private let logger: Logger = resolve(\PrivyContainer.logger)

    func generateMessage(params: SiwsMessageParams) async throws -> String {
        do {
            logger.verbose("Generating SIWS message")
            let response = try await authManager.generateSiwsMessage(for: params.address)
            let issuedAt = Date().toISO8601()

            return """
            \(params.domain) wants you to sign in with your Solana account:
            \(response.address)

            You are proving you own \(response.address).

            URI: \(params.uri)
            Version: 1
            Chain ID: mainnet
            Nonce: \(response.nonce)
            Issued At: \(issuedAt)
            Resources:
            - https://privy.io
            """
        } catch {
            logger.error("Error generating SIWS message", error: error)
            throw PrivyError(.authenticationFailure(reason: .failureDuringAuthentication(error: error)))
        }
    }

    func login(message: String, signature: String, params: SiwsMessageParams?, metadata: WalletLoginMetadata?) async throws -> any PrivyUser {
        do {
            logger.verbose("Logging user in via SIWS.")
            let result = try await authManager.loginWithSiws(address: params?.address, signing: message, with: signature, metadata: metadata)
            logger.verbose("Authenticated with SIWS successfully")
            return result
        } catch let privyError as PrivyError {
            throw privyError
        } catch {
            logger.error("Error authenticating with SIWS", error: error)
            throw PrivyError(.authenticationFailure(reason: .failureDuringAuthentication(error: error)))
        }
    }

    func link(message: String, signature: String, params: SiwsMessageParams?, metadata: WalletLoginMetadata?) async throws -> PrivyUser {
        do {
            logger.verbose("Linking account via SIWS.")

            // ensure user is authenticated before linking
            let _ = try authManager.ensureAuthenticated()

            let user = try await authManager.linkWithSiws(address: params?.address, signing: message, with: signature, metadata: metadata)
            logger.verbose("Linked with SIWS successfully")
            return user
        } catch let privyError as PrivyError {
            throw privyError
        } catch {
            logger.error("Error linking with SIWS", error: error)
            throw PrivyError(.authenticationFailure(reason: .failureDuringAuthentication(error: error)))
        }
    }

    func unlink(address: String) async throws -> PrivyUser {
        do {
            logger.verbose("Unlinking SIWS wallet.")
            // ensure user is authenticated before unlinking
            _ = try authManager.ensureAuthenticated()
            return try await authManager.unlinkSiwsWallet(address: address)
        } catch {
            logger.error("Error unlinking SIWS wallet", error: error)
            throw PrivyError(.authenticationFailure(reason: .failureDuringAuthentication(error: error)))
        }
    }

    func transferAccount(nonce: String, message: String, signature: String, params: SiwsMessageParams, metadata: WalletLoginMetadata?) async throws -> PrivyUser {
        logger.verbose("Transferring SIWS account")

        let _ = try authManager.ensureAuthenticated()

        do {
            let result = try await authManager.transferAccount(
                with: .siws(
                    message: message,
                    signature: signature,
                    walletAddress: params.address,
                    walletClientType: metadata?.walletClientType,
                    connectorType: metadata?.connectorType,
                    nonce: nonce
                )
            )

            logger.verbose("Transferred SIWS account successfully")

            return result
        } catch let privyError as PrivyError {
            throw privyError
        } catch {
            logger.error("Error transferring SIWS account", error: error)
            throw PrivyError(.authenticationFailure(reason: .failureDuringAuthentication(error: error)))
        }
    }
}
